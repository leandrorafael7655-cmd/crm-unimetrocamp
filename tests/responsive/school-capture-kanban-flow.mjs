import assert from "node:assert/strict"

const uid = (n) => `10000000-0000-4000-8000-${String(n).padStart(12, "0")}`
export async function verifyCaptureKanban({page, check, width, settle, engine}) {
  const board = page.locator("[data-capture-kanban]")
  const column = (id) => board.locator(`[data-capture-column="${id}"]`)
  const card = (id) => column(id).locator(`[data-capture-card="${uid(90)}"]`)
  const dialog = () => page.locator("dialog[open]").last()
  const save = async (label = "Salvar registro") => {
    await dialog().getByRole("button", {name: label, exact: true}).click()
    await page.waitForFunction(() => document.querySelectorAll("dialog[open]").length === 0)
    await settle()
  }
  const quick = () => page.getByRole("button", {name: "Precisam de atendimento e agendamento", exact: true})
  await page.getByRole("button", {name: "Kanban", exact: true}).click()
  assert.equal(await card("performed").count(), 1)
  assert.match(await card("performed").innerText(), /24\/10\/2026/)
  assert.match(await card("performed").innerText(), /28\/09\/2026/)
  assert.equal(await card("scheduled").count(), 0)
  await check(`Kanban completed with next appointment ${width}`)

  await page.getByLabel("Nome da escola", {exact: true}).fill("mapeada")
  await page.getByRole("button", {name: "Lista", exact: true}).click()
  assert.equal(await page.getByLabel("Nome da escola", {exact: true}).inputValue(), "mapeada")
  assert.equal(await page.getByLabel("Edição do SuperVestibular").inputValue(), uid(27))
  await page.getByRole("button", {name: "Kanban", exact: true}).click()
  await page.getByRole("button", {name: "Por consultor", exact: true}).click()
  assert.equal(await card(uid(1)).count(), 1)
  assert.equal(await card(uid(2)).count(), 1)
  assert.match(await page.locator('[data-capture-metric="performed"]').innerText(), /\b1\b/)
  await check(`Kanban principal and support unique general count ${width}`)
  await page.getByLabel("Consultor atuando").selectOption(uid(2))
  assert.equal(await board.locator("[data-capture-card]").count(), 0)
  await page.getByLabel("Consultor atuando").selectOption("")
  await page.getByLabel("Consultor que realizou atendimento").selectOption(uid(2))
  assert.equal(await card(uid(2)).count(), 1)
  await check(`Kanban separates closed engagement from performed participation ${width}`)

  await page.getByLabel("Edição do SuperVestibular").selectOption(uid(28))
  await page.getByRole("button", {name: "Por situação", exact: true}).click()
  assert.equal(await card("no_contact").count(), 1)
  assert.equal(await card("ready_to_schedule").count(), 0)
  assert.equal(await card("performed").count(), 0)
  assert.equal(await card("no_contact").getByRole("button", {name: "Agendar ação", exact: true}).isEnabled(), true)
  await check(`Kanban mapped school remains pending in 2028 ${width}`)

  await card("no_contact").getByRole("button", {name: "Registrar contato", exact: true}).click()
  assert.match(await dialog().innerText(), /Escola mapeada de teste · SuperVestibular 2028/)
  await dialog().getByLabel("Situação da negociação *").selectOption("em_negociacao")
  await dialog().getByLabel("Data *", {exact: true}).fill("2026-09-28")
  await dialog().getByLabel("Horário *", {exact: true}).fill("14:35")
  await dialog().getByLabel("Pessoa contatada *").fill("Direção de teste")
  await dialog().getByLabel("Descrição do contato *").fill("Negociação, sem ação de divulgação realizada.")
  await dialog().getByLabel("Próximo passo", {exact: true}).fill("Confirmar disponibilidade "+"DetalheExtenso".repeat(15))
  await dialog().getByLabel("Data de retorno (opcional)").fill("2026-09-30")
  await check(`Kanban quick contact form ${width}`)
  await save()
  await quick().click()
  assert.equal(await card("negotiating").count(), 1)
  assert.match(await card("negotiating").innerText(), /Retorno vencido/)
  assert.match(await page.locator('[data-capture-metric="to_schedule"]').innerText(), /\b2\b/)
  await check(`Kanban negotiation remains in needs attention filter ${width}`)

  await card("negotiating").getByRole("button", {name: "Registrar contato", exact: true}).click()
  await dialog().getByLabel("Situação da negociação *").selectOption("agendamento_conjunto")
  await dialog().getByLabel("Data *", {exact: true}).fill("2026-09-30")
  await dialog().getByLabel("Horário *", {exact: true}).fill("14:35")
  await dialog().getByLabel("Pessoa contatada *").fill("Direção de teste")
  await dialog().getByLabel("Descrição do contato *").fill("Escola confirmou disponibilidade. Pronta para registrar a ação.")
  await save()
  assert.equal(await card("ready_to_schedule").count(), 1)
  await check(`Kanban explicit readiness ${width}`)

  async function schedule(date) {
    await card("ready_to_schedule").getByRole("button", {name: "Agendar ação", exact: true}).click()
    assert.match(await dialog().innerText(), /Escola mapeada de teste · SuperVestibular 2028/)
    await dialog().getByLabel("Data *", {exact: true}).fill(date)
    await dialog().getByLabel("Horário inicial *").fill("10:00")
    await dialog().getByLabel("Horário final *").fill("11:00")
    await dialog().getByLabel("Consultor principal da ação *").selectOption(uid(2))
    await dialog().getByLabel("Local *", {exact: true}).fill("Sala de aula da escola")
    await check(`Kanban shared scheduling form ${width}`)
    await save()
  }
  await schedule("2026-10-24")
  assert.equal(await board.locator(`[data-capture-card="${uid(90)}"]`).count(), 0)
  await quick().click()
  await card("scheduled").waitFor({state: "visible"})
  assert.equal(await card("scheduled").count(), 1)
  assert.match(await page.getByRole("link", {name: "Agenda High School", exact: true}).getAttribute("href"), new RegExp(uid(28)))
  await check(`Kanban valid schedule moves school ${width}`)
  await page.evaluate((cycle) => window.showCaptureAgendaFixture(cycle), uid(28))
  await page.getByRole("heading", {name: "Agenda de ações", exact: true}).waitFor()
  assert.equal(await page.getByText("Escola mapeada de teste", {exact: true}).count(), 1)
  assert.match(await page.locator(".uni-main").innerText(), /24\/10\/2026/)
  assert.match(await page.locator(".uni-main").innerText(), /SuperVestibular 2028/)
  await check(`Kanban appointment read by existing High School agenda ${width}`)
  await page.evaluate(() => window.refreshFixture())
  await page.getByLabel("Edição do SuperVestibular").selectOption(uid(28))
  await page.getByRole("button", {name: "Kanban", exact: true}).click()
  await card("scheduled").waitFor({state: "visible"})
  assert.equal(await card("scheduled").count(), 1)

  await card("scheduled").getByRole("button", {name: "Abrir histórico da escola", exact: true}).click()
  await dialog().getByRole("button", {name: "Editar / cancelar / reagendar", exact: true}).click()
  await dialog().getByLabel("Situação da ação *").selectOption("cancelada")
  await dialog().getByRole("button", {name: "Salvar registro", exact: true}).click()
  await page.waitForFunction(() => document.querySelectorAll("dialog[open]").length === 1)
  await dialog().getByRole("button", {name: "Fechar Escola mapeada de teste", exact: true}).click()
  await settle()
  assert.equal(await card("ready_to_schedule").count(), 1)
  assert.match(await card("ready_to_schedule").innerText(), /Ação cancelada: reagendar/)
  await quick().click()
  assert.equal(await card("ready_to_schedule").count(), 1)
  await check(`Kanban canceled action returns school to scheduling ${width}`)
  await schedule("2026-10-25")
  await quick().click()
  await card("scheduled").getByRole("button", {name: "Registrar realização", exact: true}).click()
  assert.equal(await dialog().getByLabel("Consultor principal da ação *").inputValue(), uid(2))
  await dialog().getByLabel("Data *", {exact: true}).fill("2026-09-30")
  await check(`Kanban realization of existing appointment ${width}`)
  await save()
  assert.equal(await card("performed").count(), 1)
  assert.match(await card("performed").innerText(), /resultado\(s\) pendente/)
  await card("performed").getByRole("button", {name: "Registrar resultado", exact: true}).click()
  for (const name of ["em3-leads", "em3-pending", "em3-registrations"]) await dialog().locator(`[name="${name}"]`).fill("0")
  await dialog().getByLabel("Observações sobre os resultados").fill("Resultado zero informado pelo Kanban.")
  await check(`Kanban result form ${width}`)
  await save("Salvar resultado")
  assert.match(await card("performed").innerText(), /Resultado zero informado pelo Kanban/)
  assert.doesNotMatch(await card("performed").innerText(), /resultado\(s\) pendente/)
  await page.getByRole("button", {name: "Por consultor", exact: true}).click()
  assert.equal(await column(uid(1)).count(), 0)
  assert.equal(await card(uid(2)).count(), 1)
  assert.match(await card(uid(2)).innerText(), /Consultores atuando\s+Gestor de teste/)
  await check(`Kanban recorder receives no attendance credit ${width}`)

  await page.getByLabel("Edição do SuperVestibular").selectOption(uid(27))
  assert.equal(await card(uid(1)).count(), 1)
  assert.equal(await card(uid(2)).count(), 1)
  assert.match(await card(uid(1)).innerText(), /0 leads/)
  await page.evaluate(() => window.seedCaptureUnidentifiedFixture())
  await settle()
  assert.equal(await column("unidentified").locator("[data-capture-card]").count(), 1)
  assert.match(await page.locator('[data-capture-metric="performed"]').innerText(), /\b2\b/)
  assert.match(await column(uid(1)).locator("[data-column-count]").innerText(), /1 escola/)
  await check(`Kanban unidentified attendance preserves unique totals ${width}`)
  await page.getByLabel("Consultor que realizou atendimento").selectOption("unidentified")
  assert.equal(await board.locator("[data-capture-card]").count(), 1)
  await check(`Kanban filters and counts unidentified participation ${width}`)
  await page.getByRole("button", {name: "Limpar filtros / Todas", exact: true}).click()
  await page.getByRole("button", {name: "Por situação", exact: true}).click()
  if(width === 320 || width === 1366) await page.screenshot({path: `responsive-results/${engine}-capture-kanban-${width}.png`, fullPage: true})
}
